void PDFFireTextElementUpdater::writePageContent(PDFDocumentBuilder* builder,
                                                 const PDFDocument* document,
                                                 const PDFPage* page,
                                                 PDFPageContentEditorContentStreamBuilder& contentStreamBuilder)
{
    PDFDictionaryBuilder fontDictionary = contentStreamBuilder.getFontDictionary();
    PDFDictionaryBuilder xobjectDictionary = contentStreamBuilder.getXObjectDictionary();
    PDFDictionaryBuilder graphicStateDictionary = contentStreamBuilder.getGraphicStateDictionary();
    PDFDictionaryBuilder shadingDictionary = contentStreamBuilder.getShadingDictionary();

    builder->replaceObjectsByReferences(fontDictionary);
    builder->replaceObjectsByReferences(xobjectDictionary);
    builder->replaceObjectsByReferences(graphicStateDictionary);
    builder->replaceObjectsByReferences(shadingDictionary);

    PDFArrayBuilder array;
    array.appendItem(PDFObject::createName("FlateDecode"));

    // Compress the content stream
    QByteArray compressedData = PDFFlateDecodeFilter::compress(contentStreamBuilder.getOutputContent());
    PDFDictionaryBuilder contentDictionary;
    contentDictionary.setEntry(PDFInplaceOrMemoryString("Length"), PDFObject::createInteger(compressedData.size()));
    contentDictionary.setEntry(PDFInplaceOrMemoryString("Filter"), PDFObject::createArray(qMove(array)));
    PDFObject contentObject = PDFObject::createStream(PDFStream(qMove(contentDictionary), qMove(compressedData)));

    PDFObject pageObject = builder->getObjectByReference(page->getPageReference());

    // The new resource dictionary is created from the current one (which can also
    // be inherited from the page tree), so resources, which are not regenerated by
    // the content stream builder - for example color spaces, patterns, shadings or
    // properties - are preserved. Only the regenerated categories are replaced.
    // The current resources cannot be merged by the merge operation below, because
    // they are usually an indirect object, which is replaced as a whole.
    PDFDictionaryBuilder resourcesDictionary;
    if (const PDFDictionary* currentResourcesDictionary = document->getDictionaryFromObject(page->getResources()))
    {
        resourcesDictionary = PDFDictionaryBuilder(*currentResourcesDictionary);
    }

    auto setResources = [&resourcesDictionary](const char* key, const PDFDictionaryBuilder& dictionary)
    {
        if (!dictionary.isEmpty())
        {
            resourcesDictionary.setEntry(PDFInplaceOrMemoryString(key), PDFObject::createDictionary(dictionary));
        }
    };

    setResources("Font", fontDictionary);
    setResources("XObject", xobjectDictionary);
    setResources("ExtGState", graphicStateDictionary);
    setResources("Shading", shadingDictionary);

    PDFObjectFactory factory;
    factory.beginDictionary();
    factory.beginDictionaryItem("Resources");
    factory << resourcesDictionary;
    factory.endDictionaryItem();

    factory.beginDictionaryItem("Contents");
    factory << builder->addObject(std::move(contentObject));
    factory.endDictionaryItem();

    factory.endDictionary();

    pageObject = PDFObjectManipulator::merge(pageObject, factory.takeObject(), PDFObjectManipulator::RemoveNullObjects);
    builder->setObject(page->getPageReference(), std::move(pageObject));
}

bool PDFFireTextElementUpdater::refresh(const PDFDocument* document,
                                        PDFInteger pageIndex,
                                        const PDFEditedPageContent& pageContent,
                                        PDFEditedPageContentElementText* element,
                                        const PDFCMS* cms,
                                        QStringList* errors)
{
    if (!document || !element || pageIndex < 0 || size_t(pageIndex) >= document->getCatalog()->getPageCount())
    {
        return false;
    }

    const PDFPage* page = document->getCatalog()->getPage(pageIndex);
    if (!page)
    {
        return false;
    }

    PDFDocumentModifier modifier(document);
    PDFDocumentBuilder* builder = modifier.getBuilder();

    PDFPageContentEditorContentStreamBuilder contentStreamBuilder(const_cast<PDFDocument*>(document));
    contentStreamBuilder.setFontDictionary(pageContent.getFontDictionary());
    contentStreamBuilder.setXObjectDictionary(pageContent.getXObjectDictionary());
    contentStreamBuilder.setGraphicStateDictionary(pageContent.getGraphicStateDictionary());
    contentStreamBuilder.setShadingDictionary(pageContent.getShadingDictionary());
    contentStreamBuilder.writeEditedElement(element);

    if (errors)
    {
        *errors = contentStreamBuilder.getErrors();
    }
    contentStreamBuilder.clearErrors();

    writePageContent(builder, document, page, contentStreamBuilder);

    if (!modifier.finalize())
    {
        return false;
    }

    const PDFDocument* temporaryDocument = modifier.getDocument().get();
    const PDFPage* temporaryPage = temporaryDocument->getCatalog()->getPage(pageIndex);

    PDFFontCache fontCache(64, 64);
    PDFOptionalContentActivity activity(temporaryDocument, OCUsage::View, nullptr);
    fontCache.setDocument(PDFModifiedDocument(const_cast<PDFDocument*>(temporaryDocument), &activity));
    PDFPageContentEditorProcessor processor(temporaryPage, temporaryDocument, &fontCache, cms, &activity, QTransform(), PDFMeshQualitySettings());
    processor.processContents();

    PDFEditedPageContent content = processor.takeEditedPageContent();
    if (qEnvironmentVariableIsSet("PDFFIRE_DEBUG_TEXT"))
    {
        qInfo().noquote() << "PDFFIRE_DEBUG_TEXT refresh:" << content.getElementCount() << "elements, content:" << contentStreamBuilder.getOutputContent();
    }
    if (content.getElementCount() != 1)
    {
        return false;
    }

    const PDFEditedPageContentElementText* sourceElement = content.getElement(0)->asText();
    if (!sourceElement)
    {
        return false;
    }

    element->setState(sourceElement->getState());
    element->setTextPath(sourceElement->getTextPath());
    element->setItems(sourceElement->getItems());
    element->setTransform(sourceElement->getTransform());
    element->setClipPath(sourceElement->getClipPath());

    // The font keys of the processed page can differ from the keys of the element
    // (fonts are written under the keys of the page resources), so the font resources
    // and the text items as text must correspond to each other. The processed document
    // is temporary - font objects created only in it (for example a fallback font)
    // are not valid in the edited document.
    element->setFontResources(PDFEditedPageContentElementText::getFontResourcesValidInDocument(sourceElement->getFontResources(), temporaryDocument, document));
    element->setItemsAsText(sourceElement->getItemsAsText());
    return true;
}

bool PDFFireTextElementUpdater::setPlainText(const PDFDocument* document,
                                             PDFInteger pageIndex,
                                             const PDFEditedPageContent& pageContent,
                                             PDFEditedPageContentElementText* element,
                                             const QString& plainText,
                                             const PDFCMS* cms,
                                             QStringList* errors)
{
    if (!element)
    {
        return false;
    }

    // The element is changed only, if the refresh succeeds
    std::unique_ptr<PDFEditedPageContentElementText> copy(element->clone());
    copy->setItemsAsText(PDFEditedTextMarkup(copy->getItemsAsText()).getMarkupWithPlainText(plainText));
    if (!refresh(document, pageIndex, pageContent, copy.get(), cms, errors))
    {
        return false;
    }

    *element = *copy;
    return true;
}

std::unique_ptr<PDFEditedPageContentElementText> PDFFireTextElementUpdater::joinLineFragments(const std::vector<const PDFEditedPageContentElementText*>& fragments)
{
    if (fragments.size() < 2 || std::find(fragments.cbegin(), fragments.cend(), nullptr) != fragments.cend())
    {
        return nullptr;
    }

    // Ported from PdfCraft crates/edit/src/text.rs (compatible_word) (MIT OR Apache-2.0),
    // Copyright (c) 2026 ArtCraft Team and the PdfCraft contributors: independent text
    // objects are joined only, if they are drawn the same way - the same transformation,
    // the same spacing and the same colour.
    auto isSameTransform = [](const QTransform& a, const QTransform& b)
    {
        return qAbs(a.m11() - b.m11()) < 1e-6 && qAbs(a.m12() - b.m12()) < 1e-6 && qAbs(a.m21() - b.m21()) < 1e-6 &&
               qAbs(a.m22() - b.m22()) < 1e-6 && qAbs(a.dx() - b.dx()) < 1e-6 && qAbs(a.dy() - b.dy()) < 1e-6;
    };

    const PDFEditedPageContentElementText* first = fragments.front();
    const PDFPageContentProcessorState& firstState = first->getState();
    for (const PDFEditedPageContentElementText* fragment : fragments)
    {
        const PDFPageContentProcessorState& state = fragment->getState();
        if (!isSameTransform(fragment->getTransform(), first->getTransform()) ||
            fragment->getClipPath() != first->getClipPath() ||
            fragment->getTransparencyGroup() != first->getTransparencyGroup() ||
            fragment->getItems().empty() ||
            state.getFillColor() != firstState.getFillColor() ||
            state.getStrokeColor() != firstState.getStrokeColor() ||
            state.getTextRenderingMode() != firstState.getTextRenderingMode() ||
            !qFuzzyCompare(state.getAlphaFilling(), firstState.getAlphaFilling()) ||
            !qFuzzyCompare(state.getAlphaStroking(), firstState.getAlphaStroking()) ||
            state.getBlendMode() != firstState.getBlendMode() ||
            !state.getSoftMask() != !firstState.getSoftMask())
        {
            return nullptr;
        }
    }

    std::unique_ptr<PDFEditedPageContentElementText> joined(first->clone());
    std::vector<PDFEditedPageContentElementText::Item> items = first->getItems();
    std::set<size_t> followingItems;
    QPainterPath textPath = first->getTextPath();

    for (auto it = std::next(fragments.cbegin()); it != fragments.cend(); ++it)
    {
        const PDFEditedPageContentElementText* fragment = *it;

        // The following text must start with its position (a Td or Tm command)
        if (!fragment->getItems().front().isUpdateGraphicState)
        {
            return nullptr;
        }

        for (const PDFEditedPageContentElementText::FontResource& fontResource : fragment->getFontResources())
        {
            joined->addFontResource(fontResource.font, fontResource.fontObject, fontResource.key);
        }

        followingItems.insert(items.size());
        items.insert(items.end(), fragment->getItems().cbegin(), fragment->getItems().cend());
        textPath.addPath(fragment->getTextPath());
    }

    bool isFollowingResolved = false;
    const PDFEditedPageContentElementText* joinedText = joined.get();
    auto getFontKey = [joinedText](const PDFFont* font) { return joinedText->getFontResourceKey(font); };
    const QString itemsAsText = PDFEditedPageContentElementText::createItemsAsText(firstState, items, getFontKey, &followingItems, &isFollowingResolved);
    if (!isFollowingResolved)
    {
        return nullptr;
    }

    joined->setItems(items);
    joined->setTextPath(textPath);
    joined->setItemsAsText(itemsAsText);
    return joined;
}

